const base = "http://localhost:8000";
const loginResponse = await fetch(base + "/api/auth/login", { method:"POST", headers:{"content-type":"application/json"}, body:JSON.stringify({email:"demo.patient@teleflow.local",password:"LocalDemoPatient!2026"})});
if (!loginResponse.ok) throw new Error("patient login failed");
const cookie=loginResponse.headers.get("set-cookie")?.split(";")[0];
const pdf=Buffer.from("%PDF-1.4\n1 0 obj << /Type /Catalog >> endobj\n%%EOF\n");
const form=new FormData();
form.set("file",new File([pdf],"local-demo-upload-check.pdf",{type:"application/pdf"}));
form.set("documentType","DISCHARGE_SUMMARY");
const uploadResponse=await fetch(base+"/api/documents/upload",{method:"POST",headers:{cookie},body:form});
const upload=await uploadResponse.json().catch(()=>null);
console.log("DOCUMENT_UPLOAD_HTTP="+uploadResponse.status+" OCR="+(upload?.data?.ocrStatus||"none"));
if(!uploadResponse.ok||!upload?.data?.id) throw new Error(upload?.error?.code||"document upload failed");
const documentId=upload.data.id;
const listResponse=await fetch(base+"/api/documents",{headers:{cookie}});
const list=await listResponse.json();
if(!listResponse.ok||!list.data?.documents?.some((item)=>item.id===documentId)) throw new Error("uploaded document missing from patient list");
console.log("PASS patient document list shows uploaded file");
const downloadResponse=await fetch(base+"/api/documents/"+encodeURIComponent(documentId)+"/file",{headers:{cookie}});
const downloaded=Buffer.from(await downloadResponse.arrayBuffer());
if(!downloadResponse.ok||!downloaded.toString("utf8").startsWith("%PDF-1.4")) throw new Error("encrypted document download could not be decrypted");
console.log("PASS encrypted document download/decryption");
